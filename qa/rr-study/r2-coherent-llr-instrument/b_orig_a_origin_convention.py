def _argmin_with_tie(cells: dict, key: str):
    vals = [(q, c[key]) for q, c in cells.items() if c[key] is not None]
    if not vals:
        return None, True   # no successful extraction at all -> treated as undecidable
    min_val = min(v for _, v in vals)
    winners = sorted(q for q, v in vals if v == min_val)
    tied = len(winners) > 1
    q_best = min(winners, key=lambda q: abs(cells[q]["m"]))
    return q_best, tied


def compute_argmins(trials: list[dict], log) -> dict:
    n_undecidable = 0
    for tr in trials:
        q_g, tied_g = _argmin_with_tie(tr["cells"], "ne_grid")
        q_c, tied_c = _argmin_with_tie(tr["cells"], "ne_coh")
        undecidable = tied_g or tied_c
        tr["q_grid"] = q_g
        tr["q_coh"] = q_c
        tr["undecidable"] = undecidable
        if undecidable:
            n_undecidable += 1
            tr["G"] = None
            tr["C"] = None
        else:
            tr["G"] = q_g - tr["k_true"]
            tr["C"] = q_c - tr["k_true"]
    frac_undecidable = n_undecidable / len(trials)
    log("  ROW 0a: %d/%d trials undecidable (grid-or-coherent argmin tied across >=2 cells), "
        "frac=%.3f, bar<=%.2f" % (n_undecidable, len(trials), frac_undecidable,
                                    UNDECIDABLE_FRAC_MAX))
    return {"n_undecidable": n_undecidable, "n_total": len(trials),
            "frac_undecidable": frac_undecidable, "passed": frac_undecidable <= UNDECIDABLE_FRAC_MAX}


