# =====================================================================================
# ROW 0b -- decoder-independent energy-onset detector (HK-026)
# =====================================================================================

def measure_onset_s(clean: np.ndarray, fs: int) -> float:
    """Finds the first sample where the CLEAN render's smoothed instantaneous power
    crosses ONSET_THRESHOLD_FRACTION of its own peak, with linear sub-sample
    interpolation across the crossing. No decoder, no lattice, no ft8_lib call, no
    knowledge of the FT8 symbol structure is involved -- this is purely a threshold on
    the rendered waveform's own energy envelope (HK-026: the instrument under test
    cannot be used to bound its own blind spot). A small, constant detection lag from
    modulator.py's 10ms raised-cosine fade-in is expected and is identical across every
    trial (same fade shape, same threshold) -- it is well inside ROW 0b's 0.04s (0.5
    quantum) tolerance and does not bias the RELATIVE (per-trial) truth measurement."""
    power = clean.astype(np.float64) ** 2
    win = max(1, int(round(ONSET_SMOOTH_WINDOW_S * fs)))
    if win % 2 == 0:
        win += 1
    kernel = np.ones(win, dtype=np.float64) / win
    smoothed = np.convolve(power, kernel, mode="same")
    peak = float(np.max(smoothed))
    if peak <= 0.0:
        raise RuntimeError("onset detector: rendered signal has zero power -- degenerate render")
    threshold = ONSET_THRESHOLD_FRACTION * peak
    above = np.where(smoothed >= threshold)[0]
    if above.size == 0:
        raise RuntimeError("onset detector: no samples crossed the threshold -- degenerate render")
    idx = int(above[0])
    if idx == 0:
        return 0.0
    y0, y1 = smoothed[idx - 1], smoothed[idx]
    frac = 0.0 if y1 == y0 else (threshold - y0) / (y1 - y0)
    frac = min(max(frac, 0.0), 1.0)
    return (idx - 1 + frac) / fs


