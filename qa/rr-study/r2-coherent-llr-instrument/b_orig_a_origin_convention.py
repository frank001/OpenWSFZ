def sweep_all(ex: CoherentExtractLLRs, trials: list[dict], snr_db: float, m_range, log) -> None:
    """Populates trial['cells'][q] = {'m', 'ne_grid', 'hd_grid', 'ne_coh', 'hd_coh'} for
    every q = k_true + m, m in m_range. Full recompute (no memoisation) -- spec Sec.6.6
    budgets generously; recompute is simpler and avoids partial-memoisation bugs when
    ROW 0c widens the range."""
    from synth import channel  # noqa: PLC0415

    t0 = time.time()
    n_calls = 0
    for tr in trials:
        true_bits = ex.true_codeword(tr["message"])
        assert true_bits is not None
        noisy = channel.add_noise(tr["clean"], snr_db, NOISE_SEED_BASE + tr["index"],
                                   SAMPLE_RATE_HZ)
        noisy = np.ascontiguousarray(noisy, dtype=np.float32)
        cells = tr.setdefault("cells", {})
        for m in m_range:
            q = tr["k_true"] + m
            if q in cells:
                continue
            time_offset_s = q * TIME_QUANTUM_S
            rc_g, llr_g = ex.extract_at(noisy, BASE_FREQ_HZ, time_offset_s)
            rc_c, llr_c = ex.coherent_extract_at(noisy, BASE_FREQ_HZ, time_offset_s)
            ne_g = _n_err(llr_g, true_bits) if (rc_g == 0 and llr_g is not None) else None
            ne_c = _n_err(llr_c, true_bits) if (rc_c == 0 and llr_c is not None) else None
            hd_g = _hard_bits(llr_g) if llr_g is not None else None
            hd_c = _hard_bits(llr_c) if llr_c is not None else None
            cells[q] = {"m": m, "ne_grid": ne_g, "hd_grid": hd_g, "ne_coh": ne_c, "hd_coh": hd_c}
            n_calls += 1
    log("  swept %d new row-cells (snr_db=%.1f) in %.1fs" % (n_calls, snr_db, time.time() - t0))


