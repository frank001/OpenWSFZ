def build_trials(log) -> list[dict]:
    from synth import encoder  # noqa: PLC0415

    frac_values = tuple(round(v, 6) for v in np.linspace(0.0, SYMBOL_PERIOD_S, N_SUBSYM,
                                                           endpoint=False))
    log("  sub-symbol dt_cmd fractions (%d distinct values spanning one %.2fs symbol): %s"
        % (N_SUBSYM, SYMBOL_PERIOD_S, frac_values))

    trials = []
    for i in range(N_TRIALS):
        msg = _message_for_trial(i)
        dt_cmd = round(BASE_DT_S + frac_values[i % N_SUBSYM], 6)
        clean = encoder.encode_message(msg, base_freq_hz=BASE_FREQ_HZ, dt_s=dt_cmd,
                                        snr_db=None, seed=0, sample_rate_hz=SAMPLE_RATE_HZ)
        clean = np.ascontiguousarray(clean, dtype=np.float64)
        assert clean.shape == (BUFFER_SAMPLES,), clean.shape
        t_true = measure_onset_s(clean, SAMPLE_RATE_HZ)
        k_true = int(round(t_true / TIME_QUANTUM_S))
        trials.append({
            "index": i, "message": msg, "dt_cmd": dt_cmd,
            "clean": clean.astype(np.float32), "t_true_s": t_true, "k_true": k_true,
        })
    log("  built %d trials (messages distinct via r2_sign_test._message_for_trial, "
        "N_SUBSYM=%d recurring dt_cmd values, BASE_DT_S=%.3f)" % (N_TRIALS, N_SUBSYM, BASE_DT_S))
    return trials


def check_row0b(trials: list[dict], log) -> dict:
    diffs = [abs(t["t_true_s"] - t["dt_cmd"]) for t in trials]
    tol_s = TRUTH_TOL_QUANTA * TIME_QUANTUM_S
    n_agree = sum(1 for d in diffs if d <= tol_s)
    frac_agree = n_agree / len(trials)
    passed = frac_agree >= TRUTH_AGREEMENT_MIN_FRAC
    log("  ROW 0b: truth axis (measured onset vs commanded dt_cmd) -- tol=%.3fs (%.1f quantum), "
        "n_agree=%d/%d (%.3f), bar=%.2f -> %s"
        % (tol_s, TRUTH_TOL_QUANTA, n_agree, len(trials), frac_agree, TRUTH_AGREEMENT_MIN_FRAC,
           "PASS" if passed else "FAIL"))
    log("  ROW 0b: max |t_true - dt_cmd| observed = %.4fs, mean = %.4fs"
        % (max(diffs), float(st.mean(diffs))))
    return {"n_agree": n_agree, "n_total": len(trials), "frac_agree": frac_agree,
            "tol_s": tol_s, "bar": TRUTH_AGREEMENT_MIN_FRAC, "passed": passed,
            "max_abs_diff_s": max(diffs), "mean_abs_diff_s": float(st.mean(diffs))}


