def mode_and_frac(trials: list[dict], key: str, log, label: str) -> dict:
    decidable = [tr[key] for tr in trials if not tr["undecidable"]]
    if not decidable:
        raise RuntimeError("no decidable trials for %s -- cannot compute a mode" % label)
    counts: dict[int, int] = {}
    for v in decidable:
        counts[v] = counts.get(v, 0) + 1
    mode_val = max(counts, key=lambda k: (counts[k], -abs(k)))  # tie-break: smaller |value|
    frac = counts[mode_val] / len(decidable)
    log("  %s: mode=%+d frac_at_mode=%.3f (n_decidable=%d) histogram=%s"
        % (label, mode_val, frac, len(decidable),
           {k: counts[k] for k in sorted(counts)}))
    return {"mode": mode_val, "frac_at_mode": frac, "n_decidable": len(decidable),
            "histogram": {str(k): counts[k] for k in sorted(counts)}}


