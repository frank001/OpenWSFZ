def secondary_sign_agreement(trials: list[dict], log) -> dict:
    """Per-bit sign-agreement rate between coherent @ (k+2+m) and grid @ (k+2), as a
    function of m. Confounded by C1 (LLR fusion across n_syms) -- report the curve, draw
    NO conclusion, do not let it influence the ROW (spec Sec.6.5)."""
    log("\n" + "-" * 90)
    log("SECONDARY (Sec.6.5, NOT GATED) -- sign-agreement rate: coherent @ (k+2+m) vs "
        "grid @ (k+2), as a function of m. Confounded by C1 fusion across n_syms -- "
        "report only, no conclusion drawn, does not influence the ROW.")
    log("-" * 90)
    curve = {}
    for m in SECONDARY_M_RANGE:
        per_trial_agree = []
        for tr in trials:
            q_grid_fixed = tr["k_true"] + 2
            q_coh_m = tr["k_true"] + 2 + m
            cg = tr["cells"].get(q_grid_fixed)
            cc = tr["cells"].get(q_coh_m)
            if cg is None or cc is None or cg["hd_grid"] is None or cc["hd_coh"] is None:
                continue
            hd_g, hd_c = cg["hd_grid"], cc["hd_coh"]
            agree = sum(1 for a, b in zip(hd_g, hd_c) if a == b) / len(hd_g)
            per_trial_agree.append(agree)
        if per_trial_agree:
            mean_agree = float(st.mean(per_trial_agree))
            curve[m] = {"mean_agreement": mean_agree, "n_trials": len(per_trial_agree)}
            log("  m=%+3d  mean_sign_agreement=%.4f  (n_trials=%d)"
                % (m, mean_agree, len(per_trial_agree)))
        else:
            curve[m] = {"mean_agreement": None, "n_trials": 0}
            log("  m=%+3d  no trials with valid cells at both required offsets" % m)
    peak_m = max((m for m in curve if curve[m]["mean_agreement"] is not None),
                 key=lambda m: curve[m]["mean_agreement"], default=None)
    if peak_m is not None:
        log("  peak at m=%+d (mean_agreement=%.4f) -- derivation predicts m=-2, reported for "
            "context ONLY, not scored, not gating." % (peak_m, curve[peak_m]["mean_agreement"]))
    return {"m_range": list(SECONDARY_M_RANGE), "curve": {str(k): v for k, v in curve.items()},
            "peak_m": peak_m}


