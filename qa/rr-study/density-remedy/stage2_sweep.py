def fbits(x):
    return struct.pack("<f", float(x)).hex()


def cmd_job(a):
    cells = build_cells()
    cell, p = cells[a.cell], a.pair
    setname, kind = a.set, a.kind
    n = N_CLASS if setname == "class" else N_MEAS
    base = CLASS_BASE if setname == "class" else MEAS_BASE
    assert kind in ("v0", "var") and not (setname == "class" and kind == "var")
    out = os.path.join(OUT_DIR, "%s_%s_c%02d_p%d.jsonl" % (setname, kind, a.cell, p))
    os.makedirs(OUT_DIR, exist_ok=True)
    S1.ensure_ignored(out)
    d, sha = H.load_new_dll()                       # SHA + version pin, or ROW 0a STOP
    H.CFG["supp"] = None
    sh = S1.Shim(os.path.join(H.BIN_DIR, "libft8_NEW.dll"), "NEW", has_probe=False)
    S1.LIVE_NHARD = 40
    sh.set_params(S1.LIVE_PASS2)                    # (10, 0.10, 40); the SUPPRESSION setter is not touched here
    tbl = {e["name"]: e for e in H.read_table(d)}
    table_ok = (tbl["k_min_score_pass2"]["value"] == 10.0 and tbl["osd_nhard_max"]["value"] == 40.0
                and tbl["osd_corr_threshold"]["value"] == H.f32(0.10))
    rc, sp = H.get_supp(d)
    defaults_ok = (rc == 0 and H.bits3(sp) == H.bits3(DEFAULT_TRIPLE))
    sig, target, f_msg, others, truth = signals_for(cell, p)
    todo = [None] if kind == "v0" else [v for v in variants() if v != DEFAULT_TRIPLE] + ["VN"]
    n_rb_bad, nrec = 0, 0
    with open(out, "w", newline="\n") as fo:
        fo.write(json.dumps({"hdr": 1, "set": setname, "kind": kind, "cell": a.cell, "pair": p, "sha": sha, "version": DLL_VER, "build": BUILD_COMMIT,
                             "table_ok": bool(table_ok), "defaults_ok": bool(defaults_ok), "n": n}) + "\n")
        for t in range(n):
            pcm = SR.render_scene(sig, SR.trial_seed(t, part_index(base, a.cell, p)))
            for v in todo:
                if v is None:
                    tri, vi = DEFAULT_TRIPLE, "V0"
                    rc, got = H.get_supp(d)                         # setter never called: must read the defaults
                else:
                    tri = DEFAULT_TRIPLE if v == "VN" else v
                    vi = "VN" if v == "VN" else vname(v)
                    assert H.set_supp(d, *tri) == 0
                    rc, got = H.get_supp(d)
                if rc != 0 or H.bits3(got) != H.bits3(tri):
                    n_rb_bad += 1
                _n, rows, pcl, canon = DP.decode(sh, pcm)
                f = int(PC._f_recovered(rows, target, f_msg))
                mask = 0
                for bi, (_st, fq, msg) in enumerate(others):
                    if PC._f_recovered(rows, fq, msg):
                        mask |= 1 << bi
                fp = [hashlib.sha1(" ".join(r["message"].split()).encode()).hexdigest()[:12] for r in rows if " ".join(r["message"].split()) not in truth]
                e_row = [r for r in rows if abs(r["freq_hz"] - SR.E_FREQ_HZ) <= PC.FREQ_TOLERANCE_HZ and PC._text_matches(r["message"], pair_msgs(p)[0])]
                fo.write(json.dumps({"t": t, "v": vi, "f": f, "m": mask, "nfp": len(fp), "fp": fp, "pc": pcl, "e": (e_row[0]["snr"] if e_row else None),
                                     "sha": hashlib.sha256(canon.encode()).hexdigest()[:16]}) + "\n")
                nrec += 1
        fo.write(json.dumps({"trailer": 1, "readback_mismatch": n_rb_bad, "records": nrec}) + "\n")


def cmd_plan(a):
    """Prints the job list for a phase: 'class' (V0 only, classification) or 'meas' (V0, V0 rerun, variants)."""
    cells = build_cells()
    lines = []
    for c in range(len(cells)):
        for p in range(N_PAIRS):
            if a.phase == "class":
                lines.append("job --set class --kind v0 --cell %d --pair %d" % (c, p))
            else:
                lines.append("job --set meas --kind v0 --cell %d --pair %d" % (c, p))
                lines.append("job --set meas2 --kind v0 --cell %d --pair %d" % (c, p))
                lines.append("job --set meas --kind var --cell %d --pair %d" % (c, p))
    print("\n".join(lines))


# ── loading ────────────────────────────────────────────────────────────────────
def load_job(setname, kind, c, p):
    path = os.path.join(OUT_DIR, "%s_%s_c%02d_p%d.jsonl" % (setname, kind, c, p))
    if not os.path.exists(path):
        return None
    hdr, trailer, recs = None, None, []
    with open(path) as f:
        for line in f:
            o = json.loads(line)
            if "hdr" in o:
                hdr = o
            elif "trailer" in o:
                trailer = o
            else:
                recs.append(o)
    return {"hdr": hdr, "trailer": trailer, "recs": recs, "path": path}


def file_sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def median(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2] if xs else None


# ── classify (phase A gate) ────────────────────────────────────────────────────
def cmd_classify(a):
    cells = build_cells()
    R = {"build": BUILD_COMMIT, "dll_sha256": DLL_SHA, "excluded": {}, "prod": {}, "e_reported_median": {}}
    fails, missing = [], []
    excl_units = []
    near = 0
    fp_rows = fp_scenes = 0
    se1 = math.sqrt(PROD_EXCLUDED * (1 - PROD_EXCLUDED) / N_CLASS)
    e_by_cell = {}
    for c in range(len(cells)):
        for p in range(N_PAIRS):
            j = load_job("class", "v0", c, p)
            if j is None or j["trailer"] is None or len(j["recs"]) != N_CLASS:
                missing.append((c, p)); continue
            if j["hdr"]["sha"] != DLL_SHA or not j["hdr"]["table_ok"] or not j["hdr"]["defaults_ok"] or j["trailer"]["readback_mismatch"] != 0:
                fails.append("ROW 0a: class c%d p%d header/readback" % (c, p))
            prod = sum(r["f"] for r in j["recs"]) / float(N_CLASS)
            fp_rows += sum(r["nfp"] for r in j["recs"]); fp_scenes += len(j["recs"])
            R["prod"]["%d,%d" % (c, p)] = prod
            if prod <= PROD_EXCLUDED:
                excl_units.append((c, p))
            if abs(prod - PROD_EXCLUDED) <= se1:
                near += 1
            e_by_cell.setdefault(c, []).extend(r["e"] for r in j["recs"] if r["e"] is not None)
    if missing:
        log("INCOMPLETE: %d class jobs missing/short: %r" % (len(missing), missing[:6])); sys.exit(3)
    cov = {}
    for c, lst in e_by_cell.items():
        med = median(lst)
        R["e_reported_median"][cells[c]["key"]] = med
        cov.setdefault((cells[c]["delta_hz"], subband(med)), []).append(cells[c]["key"])
    row0 = {}
    row0["0a"] = not fails
    row0["0c"] = (len(excl_units) >= MIN_EXCL_UNITS and len({c for c, _ in excl_units}) >= MIN_EXCL_CELLS and len({p for _, p in excl_units}) >= MIN_EXCL_PAIRS)
    row0["0f"] = SMOKE or all((d, sb) in cov for d in DELTAS for sb in SUBBANDS)
    fpb_v0 = 1000.0 * fp_rows / fp_scenes
    fp_branch = "B" if fpb_v0 >= FP_BRANCH_B_FROM else "A"
    fp_near_bar = FP_NEAR_LO <= fpb_v0 <= FP_NEAR_HI
    R["fp_branch"], R["fp_near_bar"] = fp_branch, fp_near_bar
    R["v0_class_fpb_per_1000"], R["v0_class_fp_rows"], R["v0_class_scenes"] = fpb_v0, fp_rows, fp_scenes
    R["row0"] = row0
    R["excluded_units"] = [[c, p] for c, p in excl_units]
    R["n_excluded_units"], R["n_excluded_cells"], R["n_excluded_pairs"] = len(excl_units), len({c for c, _ in excl_units}), len({p for _, p in excl_units})
    R["n_within_1se_of_boundary"] = near
    R["boundary_1se"] = se1
    R["coverage_measured"] = {"%s|%s" % k: v for k, v in sorted(cov.items())}
    R["fails"] = fails
    R["verdict"] = "CLASSIFICATION OK - measurement may be armed" if all(row0.values()) else "ROW 0 STOP: " + ",".join(k for k, v in row0.items() if not v)
    p = os.path.join(OUT_DIR, "classification.json")
    S1.ensure_ignored(p)
    with open(p, "w") as f:
        json.dump(R, f, indent=1)
    log(R["verdict"])
    log("V0 classification FPb = %.2f per 1,000 scenes (%d junk rows in %d scenes) -> FP clause BRANCH %s%s" % (fpb_v0, fp_rows, fp_scenes, fp_branch, " (NEAR-BAR 0.95-1.16, resolves to B)" if fp_near_bar else ""))
    log("excluded units %d (cells %d, pairs %d); within 1 SE (%.3f) of 0.20: %d of %d units" % (R["n_excluded_units"], R["n_excluded_cells"], R["n_excluded_pairs"], se1, near, len(cells) * N_PAIRS))
    for d in DELTAS:
        log("  delta %5.2f: %s" % (d, "  ".join("%s=%d" % (sb, len(cov.get((d, sb), []))) for sb in SUBBANDS)))
    per_cell = {}
    for c, p_ in excl_units:
        per_cell[c] = per_cell.get(c, 0) + 1
    log("  excluded pairs per cell: " + ", ".join("%s:%d" % (cells[c]["key"], k) for c, k in sorted(per_cell.items())))
    sys.exit(0 if all(row0.values()) else 1)


# ── verdict (phase B) ──────────────────────────────────────────────────────────
def cmd_verdict(a):
    cells = build_cells()
    vs = variants()
    with open(os.path.join(OUT_DIR, "classification.json")) as f:
        CL = json.load(f)
    excl = {(c, p) for c, p in CL["excluded_units"]}
    R = {"build": BUILD_COMMIT, "dll_sha256": DLL_SHA, "classification": {k: CL[k] for k in ("n_excluded_units", "n_excluded_cells", "n_excluded_pairs", "n_within_1se_of_boundary")}}
    # ---- load
    V0, V0B, VAR = {}, {}, {}
    fails, hdr_bad, rb_bad, short = [], 0, 0, []
    for c in range(len(cells)):
        for p in range(N_PAIRS):
            j0, j1, jv = load_job("meas", "v0", c, p), load_job("meas2", "v0", c, p), load_job("meas", "var", c, p)
            for tag, j, exp in (("v0", j0, N_MEAS), ("v0b", j1, N_MEAS), ("var", jv, N_MEAS * 26)):
                if j is None or j["trailer"] is None or len(j["recs"]) != exp:
                    short.append((tag, c, p)); continue
                if j["hdr"]["sha"] != DLL_SHA or not j["hdr"]["table_ok"] or not j["hdr"]["defaults_ok"]:
                    hdr_bad += 1
                rb_bad += j["trailer"]["readback_mismatch"]
            if j0 and j1 and jv:
                V0[(c, p)], V0B[(c, p)], VAR[(c, p)] = j0, j1, jv
    R["row0_detail"] = {"jobs_short_or_missing": len(short), "hdr_bad": hdr_bad, "readback_mismatch": rb_bad}
    row0 = {"0g": not short}
    if short:
        R["row0"] = row0; R["verdict"] = "ROW 0 STOP: 0g (incomplete: %r)" % short[:5]
        print(json.dumps(R, indent=1)); sys.exit(3)
    row0["0a"] = (hdr_bad == 0 and rb_bad == 0)
    row0["0b"] = all(file_sha(V0[k]["path"]) == file_sha(V0B[k]["path"]) or
                     [json.dumps(r, sort_keys=True) for r in V0[k]["recs"]] == [json.dumps(r, sort_keys=True) for r in V0B[k]["recs"]] for k in V0)
    # index: per (c,p): v -> {t: rec}
    IDX = {}
    for k, j in VAR.items():
        d = {}
        for r in j["recs"]:
            d.setdefault(r["v"], {})[r["t"]] = r
        IDX[k] = d
    base = {k: {r["t"]: r for r in V0[k]["recs"]} for k in V0}
    # ---- 0c/0f were checked at classification; re-assert
    row0["0c"] = CL["row0"]["0c"]
    row0["0f"] = CL["row0"]["0f"]
    fp_branch = CL["fp_branch"]
    # ---- 0d: per-scene identity of decode sha AND of F recovery between VN and V0 (=> G(VN) - G(V0) == 0 EXACTLY, without evaluating any G)
    D_FIELDS = ("f", "m", "nfp", "pc", "e")          # 0d': every field any measure reads (S16.2)
    row0["0d"] = bool(all(IDX[k]["VN"][t][fld] == base[k][t][fld] for k in IDX for t in range(N_MEAS) for fld in D_FIELDS))
    # DISCLOSURE (S16.2): the ORIGINAL 0d (decode sha) fired; name the scenes (counts only, no text)
    orig_diff = [(cells[k[0]]["key"], k[1], t, [fld for fld in ("sha", "fp") if IDX[k]["VN"][t][fld] != base[k][t][fld]])
                 for k in sorted(IDX) for t in range(N_MEAS) if IDX[k]["VN"][t]["sha"] != base[k][t]["sha"]]
    R["row0d_original_fired"] = len(orig_diff) > 0
    R["row0d_original_differing_scenes"] = [{"cell": c_, "pair": p_, "t": t_, "fields": f_} for c_, p_, t_, f_ in orig_diff]
    R["row0d_original_n_differing"], R["row0d_original_n_compared"] = len(orig_diff), sum(len(IDX[k]["VN"]) for k in IDX)
    # ---- 0e: per-lever sensitivity, from decode-stream identity only (no outcome measure)
    diff_counts = {}
    for v in vs:
        if v == DEFAULT_TRIPLE:
            continue
        diff_counts[v] = sum(1 for k in IDX for t in range(N_MEAS) if IDX[k][vname(v)][t]["sha"] != base[k][t]["sha"])
    fam = {f: {vname(v): diff_counts[v] for v in vl} for f, vl in FAMILIES.items()}
    row0["0e"] = all(any(n > 0 for n in fam[f].values()) for f in fam)
    R["0e_family_differing_scenes"] = fam
    R["0e_all_variant_differing_scenes"] = {vname(v): diff_counts[v] for v in sorted(diff_counts)}
    R["row0"] = row0
    if SMOKE:
        log("SMOKE: ROW 0 as computed = %r -- FORCED to pass so the surface code runs; NOT a verdict" % (row0,))
        row0 = {k: True for k in row0}
    if not all(row0.values()):
        # S15.4: if any row fires, NO verdict is computed at all -- no G, H1, H2 or FP of any variant has been evaluated up to here.
        R["verdict"] = "ROW 0 STOP: " + ",".join(k for k, v in row0.items() if not v) + " (no verdict computed)"
        print(json.dumps(R, indent=1, default=str)); sys.exit(1)

    # ---- every row silent: only NOW are the measures evaluated
    def rates(name_of):
        """returns G, H1[c], H2, FPb for a variant key (None => V0)"""
        hits_ex = trials_ex = 0
        h1n, h1d = {}, {}
        rec_sum = trials = fp = 0
        for (c, p), _j in base.items():
            recs = base[(c, p)] if name_of is None else IDX[(c, p)][name_of]
            for t in range(N_MEAS):
                r = recs[t]
                trials += 1
                rec_sum += bin(r["m"]).count("1")
                fp += r["nfp"]
                if (c, p) in excl:
                    hits_ex += r["f"]; trials_ex += 1
                else:
                    h1n[c] = h1n.get(c, 0) + r["f"]; h1d[c] = h1d.get(c, 0) + 1
        return {"G": hits_ex / float(trials_ex), "H1": {c: h1n[c] / float(h1d[c]) for c in h1d}, "H1_n": h1d,
                "H2": rec_sum / (11.0 * trials), "FPb": 1000.0 * fp / trials, "trials": trials, "trials_ex": trials_ex}
    M = {"V0": rates(None)}
    for v in vs:
        if v != DEFAULT_TRIPLE:
            M[vname(v)] = rates(vname(v))
    nonex_pairs = {c: sum(1 for p in range(N_PAIRS) if (c, p) not in excl) for c in range(len(cells))}
    gated = sorted(c for c in range(len(cells)) if nonex_pairs[c] >= H1_GATE_MIN_PAIRS)
    reported_only = sorted(c for c in range(len(cells)) if 1 <= nonex_pairs[c] < H1_GATE_MIN_PAIRS)
    R["h1_gated_cells"], R["h1_reported_only_cells"] = len(gated), len(reported_only)
    R["h1_cells_not_gated"] = [cells[c]["key"] for c in range(len(cells)) if c not in gated]

    import collections

    def junk_counts(vkey):
        """B' (S16.2): scene-paired COUNT differences only; text is never read."""
        S = q2 = 0
        for k in base:
            for t in range(N_MEAS):
                dd = IDX[k][vkey][t]["nfp"] - base[k][t]["nfp"]
                S += dd
                q2 += dd * dd
        return S, math.sqrt(q2)
    v0_junk_total = sum(base[k][t]["nfp"] for k in base for t in range(N_MEAS))
    R["fp_branch"], R["v0_measurement_junk_rows"] = "B-prime (counts, S16.2)" if fp_branch == "B" else "A", v0_junk_total

    def paired(v, c):
        b = c_ = n = 0
        for p in range(N_PAIRS):
            if (c, p) in excl:
                continue
            for t in range(N_MEAS):
                fv, f0 = IDX[(c, p)][vname(v)][t]["f"], base[(c, p)][t]["f"]
                n += 1
                b += (fv == 1 and f0 == 0)
                c_ += (fv == 0 and f0 == 1)
        diff = (b - c_) / float(n)
        se = math.sqrt(max(0.0, b + c_ - (b - c_) ** 2 / float(n))) / n
        return diff, se

    rows, finals = [], []
    v0 = M["V0"]
    for v in vs:
        if v == DEFAULT_TRIPLE:
            continue
        m = M[vname(v)]
        drops = {c: v0["H1"][c] - m["H1"][c] for c in gated}
        worst_c = max(drops, key=lambda c: (drops[c], -c)) if drops else None
        h1_fail = any(m["H1"][c] < v0["H1"][c] - H1_BAR for c in gated)
        h2_fail = m["H2"] < v0["H2"] - H2_BAR
        jS, jq = junk_counts(vname(v))
        jz = (jS / jq) if jq > 0 else 0.0
        jrel = jS / float(v0_junk_total) if v0_junk_total else None
        if fp_branch == "A":
            fp_fail = m["FPb"] > v0["FPb"] + FP_BAR                                   # S5.4 exactly as written (not the branch that governs here)
        else:
            fp_fail = not (jS <= 0 or (jq > 0 and jS / jq <= FP_Z))                  # S16.2 branch B': counts, one-sided, hard z = 3.0
        gain_ok = (m["G"] - v0["G"]) >= GAIN_BAR_BENCH
        clause = "H1" if h1_fail else "H2" if h2_fail else "FP" if fp_fail else "PASS" if gain_ok else "GAIN"
        wd, wse = paired(v, worst_c) if worst_c is not None else (None, None)
        rows.append({"variant": v, "G": m["G"], "dG": m["G"] - v0["G"], "worst_cell": (cells[worst_c]["key"] if worst_c is not None else None),
                     "worst_drop": (drops[worst_c] if worst_c is not None else None), "paired_diff": wd, "paired_se": wse, "H2": m["H2"], "dH2": m["H2"] - v0["H2"],
                     "FPb": m["FPb"], "dFPb": m["FPb"] - v0["FPb"], "junk_S": jS, "junk_q": jq, "junk_z": jz, "junk_rel": jrel,
                     "clause": clause, "distance": distance(v),
                     "h1_alone": bool(h1_fail and not h2_fail and not fp_fail and gain_ok)})
        if clause == "PASS":
            finals.append(v)
    ranked = sorted(finals, key=lambda v: (-M[vname(v)]["G"], distance(v), v))
    R["finalists"] = [list(v) for v in ranked[:2]]
