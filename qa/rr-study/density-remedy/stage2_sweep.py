def gen_pairs():
    """The generator the frozen literal must equal (hash-based: independent of Python's random)."""
    LET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    calls, i = [], 0
    while len(calls) < 16:
        h = hashlib.sha256(("DENSITY-REMEDY-STAGE2-PAIRS-v1|%d" % i).encode()).digest()
        i += 1
        n = 2 + (h[1] % 2)
        c = "Q%d%s" % (h[0] % 10, "".join(LET[h[2 + k] % 26] for k in range(n)))
        if c in ORIGINAL_CALLS or c in calls:
            continue
        calls.append(c)
    return [(calls[2 * k], calls[2 * k + 1]) for k in range(8)]


