def seed_table():
    rows = []
    for setname, base, n in (("class", CLASS_BASE, N_CLASS), ("meas", MEAS_BASE, N_MEAS), ("cal", CAL_BASE, 12)):
        for ci in range(len(build_cells())):
            for p in range(N_PAIRS):
                pi = part_index(base, ci, p) if setname != "cal" else None
                if pi is None:
                    continue
                for t in range(n):
                    rows.append((setname, ci, p, t, SR.trial_seed(t, pi)))
    return rows


