    cells = build_cells()
    chk(len(cells) == INHERITED_CELLS + 7, "cell count %d != 21" % len(cells))
    chk(sum(1 for c in cells[:INHERITED_CELLS] if c["group"] == "primary") == 9 and sum(1 for c in cells[:INHERITED_CELLS] if c["group"] == "strong") == 3
        and sum(1 for c in cells[:INHERITED_CELLS] if c["group"] == "e15") == 2, "inherited composition != 9+3+2")
    cov = {}
    for c in cells:
        sb = subband(reported_snr(c["e_snr_db"]))
        c["reported_e_snr_calibrated"], c["subband_calibrated"] = reported_snr(c["e_snr_db"]), sb
        cov.setdefault((c["delta_hz"], sb), []).append(c["key"])
    for d in DELTAS:
        for sb in SUBBANDS:
            chk((d, sb) in cov, "no cell at delta %s in sub-band %s" % (d, sb))
    # variants
    vs = variants()
    chk(len(vs) == 26, "variant count")
    # seeds
    rows = seed_table()
    seeds = [r[4] for r in rows]
    chk(len(set(seeds)) == len(seeds), "seed collision inside the seed table")
    parts = {(r[0], r[1], r[2]): part_index({"class": CLASS_BASE, "meas": MEAS_BASE}[r[0]], r[1], r[2]) for r in rows}
    chk(min(parts.values()) >= 30000, "a part_index below 30000")
    chk(len(set(parts.values())) == len(parts), "part_index collision between sets/cells/pairs")
    chk(max(p for (s, _, _), p in parts.items() if s == "class") < MEAS_BASE and MEAS_BASE + 8 * len(cells) <= CAL_BASE, "set ranges overlap")
    digest = hashlib.sha256(("\n".join("%s,%d,%d,%d,%d" % r for r in rows)).encode()).hexdigest()
    man = {"build_commit": full, "dll_sha256": DLL_SHA, "shim_version": DLL_VER, "pairs": PAIRS, "n_cells": len(cells), "n_variants": len(vs),
           "variants_sorted": [list(v) for v in vs], "cells": [{k: c[k] for k in ("idx", "key", "group", "delta_hz", "e_snr_db", "f_snr_db",
                                                                                  "reported_e_snr_calibrated", "subband_calibrated")} for c in cells],
           "coverage": {"%s|%s" % k: v for k, v in sorted(cov.items())}, "n_seed_rows": len(rows), "seed_table_sha256": digest,
           "n_class_scenes": len(cells) * N_PAIRS * N_CLASS, "n_meas_scenes": len(cells) * N_PAIRS * N_MEAS,
           "jobs": {"class_v0": len(cells) * N_PAIRS, "meas_v0": len(cells) * N_PAIRS, "meas_v0_rerun": len(cells) * N_PAIRS, "meas_var": len(cells) * N_PAIRS},
           "failures": fails}
    p = os.path.join(RESULTS, "stage2_prereg_manifest.json")
    with open(p, "w") as f:
        json.dump(man, f, indent=1)
    log("preflight: %s (%d failures)  cells=%d variants=%d seed_rows=%d seed_sha=%s" % ("PASS" if not fails else "FAIL", len(fails), len(cells), len(vs), len(rows), digest[:16]))
    for m in fails:
        log("  FAIL: " + m)
    for d in DELTAS:
        log("  delta %5.2f: %s" % (d, "  ".join("%s=%d" % (sb, len(cov.get((d, sb), []))) for sb in SUBBANDS)))
    sys.exit(1 if fails else 0)


