def signals_for(cell, pair_idx):
    e_msg, f_msg = pair_msgs(pair_idx)
    base = SR.load_s8hn_signals()
    for s in base:
        if s["station"] == SR.STATION_E:
            s["message_text"] = e_msg
        elif s["station"] == SR.STATION_F:
            s["message_text"] = f_msg
    base = SR.set_station_snr(base, SR.STATION_E, cell["e_snr_db"])
    base = SR.set_station_snr(base, SR.STATION_F, cell["f_snr_db"])
    target = SR.E_FREQ_HZ + cell["delta_hz"]
    sig = SR.move_station_freq(base, SR.STATION_F, target)
    others = [(s["station"], float(s["freq_hz"]), s["message_text"]) for s in sig if s["station"] != SR.STATION_F]
    assert [o[0] for o in others] == OTHER_STATIONS, [o[0] for o in others]
    truth = {" ".join(s["message_text"].split()) for s in sig}
    assert len(truth) >= 11, "truth set collapsed: %r" % truth
    return sig, target, f_msg, others, truth


def variants():
    """SORTED by the literal triple; V0 included; H5's exact ramp excluded.  Never built from a set or dict."""
    out = []
    for lo in (-15.0, -10.0, -5.0):
        for hi in (5.0, 10.0, 15.0):
            for s in (0.0, 0.5, 1.0):
                if (lo, hi, s) != H5_TRIPLE:
                    out.append((lo, hi, s))
    out.sort()
    assert len(out) == 26 and DEFAULT_TRIPLE in out and H5_TRIPLE not in out
    return out


